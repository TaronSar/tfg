"""
Python script to test the generate_encounters module, implemented based on the Air Transport Canada Track Generation Tool from https://github.com/nrc-cnrc/Canadian-Airspace-Models/tree/main/Track%20Generation%20Tool
"""
from .generate_encounters import generate_encounter, get_encounter_from_h5

def run_multiple_encounters_demo():
    
    # Max encounters to generate for testing.
    # When generating all encounters IN YOUR CODE, do not set this parameter, or set it to None, but limit it to a small number for testing, 
    # for debugging, and to avoid long execution times.
    max_encounters = 5
    # When setting the number of encounters to None in your code, all the combinations of parameters will be generated, which will result in 
    # the generation of potentially millions of encounters. See the actual combinations in generate_encounters.py, replicated here.
    # Parameters are:
    # ownship_speeds = list(range(30, 71, 10))                      # knots
    # ownship_altitudes = [400]                                     # feet              
    # ownship_altitude_ends = list(range(300, 550, 100))            # feet
    # ownship_categories = ['HB10', 'LU10']                         # category (see genrate_trajectories_and_encounters.py)
    # ownship_straight_lines = [False]                              # Boolean
    # intruder_speeds = list(range(10, 165, 35))                    # knots
    # intruder_altitudes = list(range(300, 550, 100))               # feet
    # intruder_altitude_ends = list(range(300, 550, 100))           # feet
    # intruder_categories = ['G', 'HB10', 'LU10', 'U']              # category (see genrate_trajectories_and_encounters.py)
    # intruder_azimuths = list(range(0, 360, 30))                   # degrees
    # intruder_lateral_offsets = [0, NMAC_h, WC_h, WC_h + 300]      # feet
    # intruder_vertical_offsets = [0, NMAC_v, WC_v, WC_v + 100]     # feet
    # intruder_straight_lines = [False]                             # Boolean
    # paths_converging = [True]                                     # Boolean
    # flight_durations = [240]                                      # seconds

    # The generate_encounters function can be used in three ways:
    # 1. return_mode="plot": generates encounters and displays them, printing the arguments for each encounter. This may be useful for 
    #    visually verifying that the encounters are being generated as expected. Note that by default, the axes are not equal, and what looks 
    #    like high altitude variations may just be a result of the aspect ratio. The initial point on each trajectory is indicated by a marker.
    # 2. return_mode="generator": returns a python generator that yields (encounter_index, args, encounter) for each generated encounter.
    #    This allows for programmatically processing each encounter as it is generated, without storing them all in memory at once.
    #    This allows generating one encounter at a time from the calling logic.
    # 3. return_mode="h5_path": generates all encounters and stores them in an HDF5 file, returning the path to the file. This is useful for 
    #    generating a large number of encounters and saving them for later analysis without overwhelming memory but it will generate very large 
    #    files when the number of encounters is high.
    # NOTE: UNITS ARE IMPERIAL (feet, knots, etc.) IN THIS TOOL, as it is based on the Air Transport Canada Track Generation Tool, and are named
    # accordingly in the arguments (e.g. ownship_altitude, ownship_speed, etc.). When using the generated encounters, make sure to convert the 
    # units as needed.
    # NOTE: The time duration of the generated encounters will in general be different from the flight_duration argument, as the encounter will 
    # be generated by the track generation tool first, and then the velocities will be adjusted to meet the ones required in the input arguments
    # which will potentially result in time adjustments. The output time vector will contain the actual time points of the encounter.
    
    # 1. Plot mode, will generate encounters and display them, printing the arguments for each encounter.
    # This may be useful for visually verifying that the encounters are being generated with the expected parameters.
    # Note that by default, the axes are not equal, and what looks like high altitude changes may just be a result of the plot aspect ratio.
    # The initial point on each trajectory is indicated by a marker.
    generate_encounter(return_mode="plot", max_encounters=max_encounters)
    
    # 2. Generator mode, will return a generator that yields (encounter_index, args, encounter) for each generated encounter.
    # This allows for programmatically processing each encounter as it is generated, without storing them all in memory at once.
    generator  = generate_encounter(return_mode="generator", max_encounters=max_encounters)
    
    for ix in range(max_encounters):
        encounter_index, args, encounter = next(generator)
        print(f"[Python Generator] encounter {encounter_index}: {args}")
    
    # 3. HDF5 mode, will generate all encounters and store them in an HDF5 file, returning the path to the file.
    # This is useful for generating a large number of encounters and saving them for later analysis without overwhelming memory
    # but it will generate very large files when the number of encounters is high.
    file_path = generate_encounter(return_mode="h5_path", max_encounters=max_encounters)
    
    for ix in range(max_encounters):
        encounter_index, args, encounter = get_encounter_from_h5(file_path, encounter_index=ix)
        print(f"[HDF5 file] Encounter {encounter_index}: {args}")        


if __name__ == "__main__":
    run_multiple_encounters_demo()

